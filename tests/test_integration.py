#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""End-to-end tests: the real CLI, real child processes, stubbed binaries.

Every test runs ``autovod.py`` as a subprocess with STREAMLINK_BIN / FFMPEG_BIN
/ RCLONE_BIN / YOUTUBE_UPLOADER_BIN pointed at the stubs in ``tests/stubs``,
so the complete record -> re-encode -> upload pipeline is exercised without
network access or real credentials.

Run with:  python -m unittest discover -s tests -t . -v
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STUBS = os.path.join(ROOT, "tests", "stubs")
AUTOVOD = os.path.join(ROOT, "autovod.py")


def native(path):
    return path.replace("\\", "/")


class IntegrationTest(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.mkdtemp(prefix="autovod-it-")
        self.addCleanup(shutil.rmtree, self.dir, True)
        self.out = os.path.join(self.dir, "out")
        self.tmp = os.path.join(self.dir, "tmp")
        self.rclone_dir = os.path.join(self.dir, "remote")
        self.argv_log = os.path.join(self.dir, "argv.log")
        self.upload_log = os.path.join(self.dir, "uploads.log")
        self.rtmp_log = os.path.join(self.dir, "rtmp.log")
        self.config_path = os.path.join(self.dir, "tester.config")

    # -- helpers ------------------------------------------------------------
    def write_config(self, sink="local", extra="", name="tester"):
        python = native(sys.executable)
        lines = [
            "# generated by the AutoVOD test suite",
            'STREAM_SOURCE="twitch"',
            'UPLOAD_SERVICE="%s"' % sink,
            'STREAMLINK_QUALITY="1080p60"',
            'QUALITY_FALLBACK="best"',
            'STREAMLINK_BIN=("%s" "%s")' % (python, native(os.path.join(STUBS, "stub_streamlink.py"))),
            'FFMPEG_BIN=("%s" "%s")' % (python, native(os.path.join(STUBS, "stub_ffmpeg.py"))),
            'RCLONE_BIN=("%s" "%s")' % (python, native(os.path.join(STUBS, "stub_rclone.py"))),
            'YOUTUBE_UPLOADER_BIN=("%s" "%s")'
            % (python, native(os.path.join(STUBS, "stub_youtubeuploader.py"))),
            'VIDEO_DURATION="00:00:05"',
            'VIDEO_TITLE="{{STREAMER}}-{{TITLE}}"',
            'VIDEO_PLAYLIST="Test VODs"',
            'VIDEO_VISIBILITY="unlisted"',
            'LOCAL_FILENAME="rec_$STREAMER_NAME"',
            'LOCAL_EXTENSION="mkv"',
            'LOCAL_DIR="out"',
            'RCLONE_FILENAME="rec_$STREAMER_NAME"',
            'RCLONE_FILEEXT="mkv"',
            'RCLONE_REMOTE="stubremote"',
            'RCLONE_DIR="vods"',
            'YOUTUBE_FILENAME="yt_$STREAMER_NAME"',
            'YOUTUBE_SECRETS="client_secrets.json"',
            'YOUTUBE_TOKEN_CACHE="request.token"',
            'RTMPS_URL="rtmp://example.test/live2/"',
            'RTMPS_STREAM_KEY="stubkey"',
            'AUDIO_BITRATE="128"',
            'STATE_DIR=".autovod"',
            'TEMP_DIR="tmp"',
            'POLL_INTERVAL="5"',
            'RECONNECT_DELAY="0"',
            'UPLOAD_RETRY_MAX="3"',
            'LOG_LEVEL="info"',
        ]
        path = self.config_path if name == "tester" else os.path.join(self.dir, name + ".config")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write("\n".join(lines) + "\n" + extra + "\n")
        # YouTube is the only sink that needs the OAuth files to exist
        for filename in ("client_secrets.json", "request.token"):
            target = os.path.join(self.dir, filename)
            if not os.path.exists(target):
                with open(target, "w", encoding="utf-8") as handle:
                    handle.write("{}")
        return path

    def run_cli(self, config_path=None, args=("--once",), env=None, timeout=120):
        environment = dict(os.environ)
        environment.update({
            "STUB_ARGV_LOG": native(self.argv_log),
            "STUB_UPLOAD_LOG": native(self.upload_log),
            "STUB_RCLONE_DIR": native(self.rclone_dir),
            "STUB_RTMP_LOG": native(self.rtmp_log),
            "STUB_TITLE": "Stub title",
        })
        environment.update(env or {})
        proc = subprocess.run(
            [sys.executable, AUTOVOD, "-c", config_path or self.config_path] + list(args),
            cwd=self.dir, env=environment, capture_output=True, text=True, timeout=timeout,
        )
        return proc

    def argv_calls(self):
        if not os.path.exists(self.argv_log):
            return []
        with open(self.argv_log, "r", encoding="utf-8") as handle:
            return [json.loads(line) for line in handle if line.strip()]

    def uploads(self):
        if not os.path.exists(self.upload_log):
            return []
        with open(self.upload_log, "r", encoding="utf-8") as handle:
            return [json.loads(line) for line in handle if line.strip()]

    def out_files(self):
        return sorted(os.listdir(self.out)) if os.path.isdir(self.out) else []

    def files(self, path):
        return sorted(os.listdir(path)) if os.path.isdir(path) else []

    # -- local --------------------------------------------------------------
    def test_local_records_a_file(self):
        self.write_config("local")
        proc = self.run_cli()
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        self.assertEqual(self.out_files(), ["rec_tester.mkv"])
        self.assertEqual(os.path.getsize(os.path.join(self.out, "rec_tester.mkv")), 4096)
        self.assertFalse(os.path.exists(os.path.join(self.out, "rec_tester.mkv.part")))
        self.assertIn("saved", proc.stdout)
        calls = [call for call in self.argv_calls()]
        self.assertTrue(any("--stdout" in call for call in calls))
        self.assertTrue(any("--hls-duration" in call for call in calls))

    def test_local_reconnects_when_the_stream_drops(self):
        self.write_config("local")
        marker = os.path.join(self.dir, "failed-once")
        proc = self.run_cli(env={"STUB_FAIL_ONCE": native(marker)})
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        # first attempt fails, the stream is still live, so the data is appended
        self.assertEqual(os.path.getsize(os.path.join(self.out, "rec_tester.mkv")), 8192)
        self.assertIn("reconnecting", proc.stdout)

    def test_offline_stream_records_nothing(self):
        self.write_config("local")
        proc = self.run_cli(env={"STUB_LIVE": "0"})
        self.assertEqual(proc.returncode, 1)
        self.assertEqual(self.out_files(), [])
        self.assertIn("offline", proc.stdout)

    def test_dry_run_does_not_touch_the_disk(self):
        self.write_config("local")
        proc = self.run_cli(args=("--once", "--dry-run"))
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        self.assertEqual(self.out_files(), [])
        self.assertIn("[dry-run]", proc.stdout)

    # -- rclone -------------------------------------------------------------
    def test_rclone_records_then_uploads(self):
        self.write_config("rclone")
        proc = self.run_cli()
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        self.assertEqual(self.files(self.rclone_dir), ["rec_tester.mkv", "targets.txt"])
        with open(os.path.join(self.rclone_dir, "targets.txt"), encoding="utf-8") as handle:
            target = handle.read().strip()
        self.assertEqual(target, "stubremote:/vods/rec_tester.mkv")
        self.assertEqual(os.path.getsize(os.path.join(self.rclone_dir, "rec_tester.mkv")), 4096)
        self.assertEqual(self.files(self.tmp), [])  # temp file cleaned up
        rclone_call = [call for call in self.argv_calls() if "copyto" in call][0]
        self.assertIn("--progress", rclone_call)

    def test_rclone_reencodes_before_uploading(self):
        self.write_config("rclone", extra='RE_ENCODE="true"\nRE_ENCODE_CODEC="libx265"\n')
        proc = self.run_cli()
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        self.assertIn("rec_tester.mkv", self.files(self.rclone_dir))
        ffmpeg_call = [call for call in self.argv_calls() if "-c:v" in call][0]
        self.assertIn("libx265", ffmpeg_call)
        self.assertIn("-f", ffmpeg_call)
        self.assertIn("matroska", ffmpeg_call)
        self.assertEqual(self.files(self.tmp), [])

    def test_rclone_failure_keeps_the_file_when_asked(self):
        self.write_config("rclone", extra='SAVE_ON_FAIL="true"\nUPLOAD_RETRY_MAX="1"\n')
        proc = self.run_cli(env={"STUB_RCLONE_EXIT": "1"})
        self.assertEqual(proc.returncode, 1)
        self.assertIn("upload failed", proc.stdout)
        self.assertEqual(self.files(os.path.join(self.dir, "tmp")), ["rec_tester.mkv"])

    def test_rclone_failure_discards_the_file_by_default(self):
        self.write_config("rclone", extra='SAVE_ON_FAIL="false"\nUPLOAD_RETRY_MAX="1"\n')
        proc = self.run_cli(env={"STUB_RCLONE_EXIT": "1"})
        self.assertEqual(proc.returncode, 1)
        self.assertEqual(self.files(self.tmp), [])

    # -- youtube ------------------------------------------------------------
    def test_youtube_records_then_uploads(self):
        self.write_config("youtube")
        proc = self.run_cli()
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        uploads = self.uploads()
        self.assertEqual(len(uploads), 1)
        self.assertEqual(uploads[0]["title"], "tester-Stub title")
        self.assertEqual(uploads[0]["privacyStatus"], "unlisted")
        self.assertEqual(uploads[0]["playlistTitles"], ["Test VODs"])
        self.assertEqual(uploads[0]["bytes"], 4096)
        self.assertNotEqual(uploads[0]["filename"], "-")
        self.assertIn("youtu.be/STUBVIDEOID1", proc.stdout)
        # the buffered part is removed after a successful upload
        self.assertEqual(self.files(self.tmp), ["yt_tester.meta.json", "yt_tester.meta.out.json"])

    def test_youtube_keeps_the_local_copy_when_configured(self):
        self.write_config("youtube", extra='YOUTUBE_KEEP_LOCAL="true"\n')
        proc = self.run_cli()
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        self.assertIn("yt_tester.mkv", self.files(self.tmp))
        self.assertIn("local copy kept", proc.stdout)

    def test_youtube_retries_a_failed_upload(self):
        self.write_config("youtube")
        marker = os.path.join(self.dir, "upload-failed-once")
        proc = self.run_cli(env={"STUB_UPLOAD_FAIL_ONCE": native(marker)})
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        self.assertEqual(len(self.uploads()), 2)
        self.assertIn("attempt 2/3", proc.stdout)

    def test_youtube_pipe_mode_has_no_local_copy(self):
        self.write_config("youtube", extra='YOUTUBE_RECORD_TO_DISK="false"\n')
        proc = self.run_cli()
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        uploads = self.uploads()
        self.assertEqual(len(uploads), 1)
        self.assertEqual(uploads[0]["filename"], "-")
        self.assertEqual(uploads[0]["bytes"], 4096)

    def test_youtube_failure_is_visible_not_silent(self):
        self.write_config("youtube")
        proc = self.run_cli(env={"STUB_UPLOAD_EXIT": "1"})
        self.assertEqual(proc.returncode, 1)
        self.assertIn("youtubeuploader exited with code 1", proc.stdout)
        self.assertIn("upload failed", proc.stdout)
        self.assertEqual(self.files(self.tmp), ["yt_tester.meta.json"])

    # -- restream -----------------------------------------------------------
    def test_restream_pipes_into_ffmpeg_with_real_audio_settings(self):
        self.write_config("restream")
        proc = self.run_cli()
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        with open(self.rtmp_log, "r", encoding="utf-8") as handle:
            record = json.loads(handle.readline())
        self.assertEqual(record["target"], "rtmp://example.test/live2/stubkey")
        self.assertEqual(record["bytes"], 4096)
        args = record["args"]
        self.assertIn("-b:a", args)
        self.assertEqual(args[args.index("-b:a") + 1], "128k")
        self.assertEqual(args[args.index("-ar") + 1], "44100")
        self.assertNotIn("-re", args)          # 2.x throttled a live source for no reason
        self.assertNotIn("44100k", args)       # 2.x used the sample rate as bitrate
        self.assertEqual(args[args.index("-f") + 1], "flv")

    # -- parts, state, locking ---------------------------------------------
    def test_second_recording_of_the_day_becomes_part_two(self):
        self.write_config("local")
        first = self.run_cli()
        second = self.run_cli()
        self.assertEqual((first.returncode, second.returncode), (0, 0))
        self.assertEqual(self.out_files(), ["rec_tester-Part_2.mkv", "rec_tester.mkv"])
        with open(os.path.join(self.dir, ".autovod", "tester.state.json"), encoding="utf-8") as handle:
            state = json.load(handle)
        self.assertEqual(state["part"], 2)

    def test_youtube_part_numbering_reaches_the_title(self):
        self.write_config("youtube")
        self.run_cli()
        self.run_cli()
        titles = [upload["title"] for upload in self.uploads()]
        self.assertEqual(titles, ["tester-Stub title", "tester-Stub title Part: 2"])

    def test_lock_prevents_a_second_instance(self):
        self.write_config("local")
        os.makedirs(os.path.join(self.dir, ".autovod"), exist_ok=True)
        lock = self.dir_lock()
        lock.acquire()
        try:
            proc = self.run_cli()
        finally:
            lock.release()
        self.assertEqual(proc.returncode, 3)
        self.assertIn("already running", proc.stdout)

    def dir_lock(self):
        sys.path.insert(0, ROOT)
        import autovod
        return autovod.FileLock(os.path.join(self.dir, ".autovod", "tester.lock"))

    # -- diagnostics --------------------------------------------------------
    def test_check_reports_a_missing_binary(self):
        self.write_config("local", extra='STREAMLINK_BIN=("no-such-streamlink-binary")\n')
        proc = self.run_cli(args=("--check",))
        self.assertEqual(proc.returncode, 2)
        self.assertIn("no-such-streamlink-binary", proc.stdout)

    def test_check_passes_with_the_stubs(self):
        self.write_config("local")
        proc = self.run_cli(args=("--check",))
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        self.assertIn("all checks passed", proc.stdout)

    def test_list_streams_reports_metadata_and_qualities(self):
        self.write_config("local")
        proc = self.run_cli(args=("--list-streams",))
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        self.assertIn("Stub title", proc.stdout)
        self.assertIn("Just Chatting", proc.stdout)
        self.assertIn("1080p60", proc.stdout)

    def test_config_warnings_are_shown(self):
        self.write_config("local", extra='SOMETHING="$NOT_DEFINED"\n')
        proc = self.run_cli(args=("--check",))
        self.assertIn("NOT_DEFINED", proc.stdout)


if __name__ == "__main__":
    unittest.main(verbosity=2)
